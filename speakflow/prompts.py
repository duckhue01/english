"""
NotebookLM Prompts & Source Document Generators for SpeakFlow.
Meticulously engineered to guide NotebookLM's multi-modal audio analysis.
"""

def generate_notebooklm_prompt(title: str, text: str, focus_notes: str = "") -> str:
    """
    Generate an expert speech coach prompt tailored for NotebookLM's chat interface.
    The user can paste this directly into NotebookLM after uploading the audio and reference doc.
    """
    focus_section = f"\nSpecific Target Focus:\n{focus_notes}\n" if focus_notes else ""
    return f"""You are an elite English Pronunciation and Speech Coach.
I have uploaded two sources for this session:
1. An audio recording of me reading the practice passage.
2. The reference text file containing the exact original script: "{title}".

Reference Script:
\"\"\"
{text}
\"\"\"{focus_section}

Please perform a thorough, diagnostic pronunciation and spoken English audit by comparing my audio against the reference script. Provide your analysis in the following structured format:

### 1. Word Accuracy & Fidelity Audit
- Identify any omitted words, added words, word substitutions, or slurred phrases.
- Provide a side-by-side comparison table: [Original Word] | [What Was Heard] | [Issue Type].

### 2. Phonetic & Pronunciation Analysis (The Core Diagnostic)
- Identify all mispronounced phonemes, distorted vowels, or unclear consonants.
- For each error, provide:
  * **Target IPA vs Perceived IPA** (e.g., target /θ/ vs perceived /s/ or /t/).
  * **Error Classification**: (e.g., consonant cluster reduction, dropped final consonant, tense vs lax vowel confusion, silent letter voiced).
  * **Physical Articulation Guide**: Exactly where to place the tongue, teeth, and lips to produce the correct sound.

### 3. Prosody, Stress, and Rhythm
- **Word-Level Stress**: Were multi-syllable words stressed on the correct syllables?
- **Sentence Stress & Rhythm**: Did I place stress on content words (nouns, verbs) rather than function words?
- **Connected Speech & Linking**: Did I link words naturally (consonant-to-vowel linking, flap-T, contractions), or was it robotic/staccato?
- **Intonation & Tone**: Was the pitch variation expressive and appropriate for the context?
- **Pacing & Breathing**: Speech rate (Words Per Minute), unnatural mid-phrase pauses, or rushed sections.

### 4. Tailored Action Drills & "Tips & Tricks"
- **3 Micro-Drills**: Targeted exercises addressing my top 2-3 pronunciation bottlenecks from this clip.
- **Minimal Pairs Practice**: 3-5 word pairs contrasting my specific phonetic errors (e.g., "think / sink", "sheep / ship").
- **Mnemonic / Physical Trick**: A memorable physical anchor or tongue-placement cue I can use immediately.

### 5. Session Score & Next Action
- Pronunciation Accuracy: [Score / 10]
- Rhythm & Intonation: [Score / 10]
- Fluency & Clarity: [Score / 10]
- Top priority to focus on for my next recording.
"""


def generate_source_document_markdown(
    title: str,
    text: str,
    session_id: str,
    timestamp: str,
    duration_str: str,
    category: str = "General Practice",
    phonetic_focus: str = "",
    difficulty: str = "Intermediate",
) -> str:
    """
    Generate the companion markdown document designed to be uploaded as a Source into NotebookLM.
    This gives NotebookLM full context of the passage, phonetics, and evaluation criteria.
    """
    word_count = len(text.split())

    focus_block = f"""
## Target Phonetic Elements & Focus Areas
{phonetic_focus}
""" if phonetic_focus else ""

    return f"""# SpeakFlow Pronunciation Practice Source
**Session Title:** {title}  
**Session ID:** `{session_id}`  
**Date & Time:** {timestamp}  
**Category:** {category}  
**Difficulty Level:** {difficulty}  
**Audio Duration:** {duration_str}  
**Target Word Count:** {word_count} words  

---

## Reference Script (Original Text to Analyze)
> The audio file uploaded with this session corresponds to the following passage. Analyze the speaker's vocal audio against this text word-for-word.

```text
{text}
```
{focus_block}
---

## Analysis Instructions for NotebookLM
When this source document is paired with the accompanying audio recording (`{session_id}_audio.m4a`):

1. **Compare Audio to Text**: Transcribe what the speaker actually articulated and compare against the Reference Script above.
2. **Phonetic Evaluation**: Detect mispronounced vowels, consonants, dropped endings (-ed, -s, -t, -d), and cluster simplifications.
3. **Acoustic & Prosodic Evaluation**: Evaluate speech tempo, intonation contours, pause placements, and stress hierarchy.
4. **Actionable Coaching**: Provide physical tongue/mouth placement tips, minimal pair contrast drills, and pronunciation tips.

---
*Generated by SpeakFlow Terminal Studio for Google NotebookLM.*
"""
